// Generates docs/PARAMETER_REFERENCE.md from the code and checks that the
// committed file matches, so the parameter documentation cannot drift from
// the parameter table, the presentation (display text) laws or the editor
// layout.
//
//   arpsid_parameter_reference_doc_tests <docs/PARAMETER_REFERENCE.md>
//       check mode: fails if the file differs from the generated text
//   arpsid_parameter_reference_doc_tests --write <docs/PARAMETER_REFERENCE.md>
//       regenerates the file (cmake --build <dir> --target arpsid_update_parameter_reference)
//
// Sources of truth
//   name, unit, default, automatable   kParamInfos (source/parameter_ids.h)
//   steps (0 = continuous)             normalizedParamStepCount
//   display text                       choice names from the editor label tables
//                                      (arpsid_editor_labels.h, engine decode
//                                      law), else SidParameterPresentation::
//                                      formatNormalized (the text hosts show)
//   editor tab / section               GUI::EditorLayout (VSTGUI editor)

#include "gui/vstgui/arpsid_editor_labels.h"
#include "gui/vstgui/arpsid_editor_layout.h"

#include "arpsid/core/sid_parameter_presentation.h"
#include "parameter_ids.h"

#include <cctype>
#include <cstdio>
#include <fstream>
